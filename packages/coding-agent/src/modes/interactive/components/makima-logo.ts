export const MAKIMA_LOGO_WIDTH = 28;
export const MAKIMA_LOGO_HEIGHT = MAKIMA_PIXEL_ART.length;

const colors = new Map<string, ReturnType<typeof rgbColor>>();

function colorFromHex(hex: string): ReturnType<typeof rgbColor> {
	const cached = colors.get(hex);
	if (cached) return cached;
	const color = rgbColor(
		Number.parseInt(hex.slice(1, 3), 16),
		Number.parseInt(hex.slice(3, 5), 16),
		Number.parseInt(hex.slice(5, 7), 16),
	);
	colors.set(hex, color);
	return color;
}

/** Makima TUI's 28×15 pixel portrait, rendered as two terminal columns per pixel. */
export function makimaLogoLines(): string[] {
	const mode = theme.getColorMode();
	return MAKIMA_PIXEL_ART.map((row) =>
		row.map((hex) => (hex ? `${backgroundAnsi(colorFromHex(hex), mode)}  ${RESET}` : "  ")).join(""),
	);
}
